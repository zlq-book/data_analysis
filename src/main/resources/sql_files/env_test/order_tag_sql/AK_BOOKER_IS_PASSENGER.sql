        WHEN MAX(CASE
                     WHEN FK_BOOKING_USER_TID IS NOT NULL
                         AND FK_PASSENGER_USER_TID IS NOT NULL
                         AND FK_BOOKING_USER_TID = FK_PASSENGER_USER_TID
                         THEN 1 ELSE 0
