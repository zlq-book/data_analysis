---- 机票预订PNR级事实表
INSERT INTO DWD_TEST.T_DWD_BOOKING_PNR_FACT (PK_ID,AK_BOOKER_IS_PASSENGER)
SELECT
    bpf.PK_ID,
    CASE
        WHEN MAX(CASE WHEN bsf.AK_BOOKER_IS_PASSENGER = 1 THEN 1 ELSE 0 END) = 1 THEN 1
        ELSE 0
        END AS AK_BOOKER_IS_PASSENGER
FROM
    DWD_TEST.T_DWD_BOOKING_PNR_FACT bpf
        LEFT JOIN
    DWD_TEST.T_DWD_BOOKING_SEG_FACT bsf
    ON
        bpf.PNR_NUMBER = bsf.PNR_NUMBER
            AND bpf.FK_PNRCREATE_DATE = bsf.FK_BOOKING_DATE
WHERE bpf.DATA_ACTIVE_TIME  BETWEEN CONCAT(@ETL_DATE,' 00:00:00.000') AND CONCAT(@ETL_DATE,' 23:59:59.999')
GROUP BY
    bpf.PK_ID,
    bpf.PNR_NUMBER,
    bpf.FK_PNRCREATE_DATE;
