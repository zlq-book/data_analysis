INSERT INTO DWD_TEST.T_DWD_TICKING_TIC_FACT (PK_ID,AK_BOOKING_PASSENGER)
SELECT
    tic.PK_ID,
    CASE
        WHEN MAX(CASE WHEN seg.AK_BOOKING_PASSENGER = 1 THEN 1 ELSE 0 END) = 1 THEN 1
        ELSE 0
        END AS AK_BOOKING_PASSENGER
FROM
    DWD_TEST.T_DWD_TICKING_TIC_FACT tic
        LEFT JOIN
    DWD_TEST.T_DWD_TICKING_SEG_FACT seg
    ON
        tic.TICKET_NUMBER = seg.AK_TICKET_NUMBER
            AND tic.FK_TICKETING_DATE = seg.FK_ISSUE_DATE
WHERE tic.DATA_ACTIVE_TIME  BETWEEN CONCAT(@ETL_DATE,' 00:00:00.000') AND CONCAT(@ETL_DATE,' 23:59:59.999')
GROUP BY
    tic.PK_ID,
    tic.TICKET_NUMBER,
    tic.FK_TICKETING_DATE;;
