INSERT INTO DIM_TEST.T_DIM_FFP_DIM (SYSTEM_KEY ,T_ID ,FFRF ,FT_REGISTER_TIME,PARENT_CARD_NUMBER ,MOST_TRUSTED_SOURCE,UPDATE_TIME,CREATE_TIME)
SELECT
TO_BASE64(SM4_ENCRYPT(REGEXP_REPLACE(SM4_DECRYPT(FROM_BASE64(a.FCARD), FROM_BASE64(@SM4_KEY)),'\\D',''), FROM_BASE64(@SM4_KEY))) AS MEM_NUM ,
TO_BASE64(SM4_ENCRYPT(REGEXP_REPLACE(SM4_DECRYPT(FROM_BASE64(a.FCARD), FROM_BASE64(@SM4_KEY)),'\\D',''), FROM_BASE64(@SM4_KEY))) AS TID ,
TO_BASE64(SM4_ENCRYPT(REGEXP_REPLACE(SM4_DECRYPT(FROM_BASE64(a.FCARD), FROM_BASE64(@SM4_KEY)),'\\D',''), FROM_BASE64(@SM4_KEY))) AS FFR ,
a.CREATE_DATE ,
TO_BASE64(SM4_ENCRYPT(REGEXP_REPLACE(SM4_DECRYPT(FROM_BASE64(a.PARENT_FFP_NUM), FROM_BASE64(@SM4_KEY)),'\\D',''), FROM_BASE64(@SM4_KEY))) AS PARENT_FFR,
'1' as SOURCE,
now() AS UPDATE_TIME,
now() AS CREATE_TIME
FROM ODS_TEST.T_ODS_CLK_FFP_REGISTER_INFO a
WHERE a.SEND_FLAG = 'Y'
AND a.SEND_STATUS = '1'
and LENGTH(SM4_DECRYPT(FROM_BASE64(a.FPHONE), FROM_BASE64(@SM4_KEY))) <15
AND a.ETL_DATE = @ETL_DATE;

