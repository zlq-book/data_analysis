--写入TID集合
INSERT INTO DIM_TEST.T_DIM_TID_SET
(TID, ETL_DATE, CREATE_TIME, TID_STATUS)
SELECT CREDENTIALNUM as STRONGID,now() AS ETL_DATE,CURRENT_TIMESTAMP(3) AS CREATE_TIME,1
FROM DIM_TEST.T_DIM_FFP_CERT_CHECK_DIM ffc
LEFT JOIN DIM_TEST.T_DIM_TID_SET tdts ON ffc.CREDENTIALNUM = tdts.TID
WHERE tdts.TID IS null;

