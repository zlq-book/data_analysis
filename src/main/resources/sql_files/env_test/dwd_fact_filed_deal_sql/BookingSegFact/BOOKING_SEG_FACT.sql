         LEFT JOIN DIM_TEST.T_DIM_ADDRESS_DIM addr_arr
                   ON t.FK_ARRIAIRPORT = addr_arr.ADDRESS_KEY -- 到达机场三字码关联
         LEFT JOIN DIM_TEST.T_DIM_PROVINCE_CITY_DIM pc
                   ON pc.ID = SUBSTRING(SM4_DECRYPT(FROM_BASE64(t.CERT_NUMBER), FROM_BASE64(@SM4_KEY)), 1,4)
                       AND pc.PROVINCE = addr_arr.PROVINCE
WHERE t.FK_DEPAIRPORT is not null
  and t.DATA_ACTIVE = 1
  and t.FK_ARRIAIRPORT is not null
  and t.CERT_NUMBER is not null
  and t.CERT_TYPE = 'NI'
