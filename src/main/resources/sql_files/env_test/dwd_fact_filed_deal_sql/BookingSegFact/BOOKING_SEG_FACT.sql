       CASE
           WHEN t.CERT_TYPE = 'NI' -- 身份证类型
               AND pc.PROVINCE = addr_arr.PROVINCE -- 与到达机场省份相同
               AND addr_dep.PROVINCE != addr_arr.PROVINCE -- 起飞机场与到达机场省份不同
               THEN 1
           ELSE 0
           END AS HOMECOMING_SEG,
       NOW() AS SYSTEM_CREATETIME,
       NOW() AS SYSTEM_LAST_UPDATETIME

