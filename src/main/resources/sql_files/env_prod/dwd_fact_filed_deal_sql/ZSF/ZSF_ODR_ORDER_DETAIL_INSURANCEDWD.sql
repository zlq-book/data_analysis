-- 掌尚飞保险订单数据写入保险事实表
-- 数据来源：T_ODS_ZSF_ODR_ORDER_DETAIL_INSURANCE (保险订单表) + T_ODS_ZSF_ODR_ORDER_CUSTOMER_RELATION (客户关系表)
-- 目标表：T_DWD_AUIS_SEG_FACT (保险事实表-航段级)
-- 业务逻辑：保险状态为3（已出单）、6（退保成功）、7（退保失败）的数据进入事实表
-- 
-- 注意：源数据库CERT_NO字段为未加密状态，需要先加密再标准化处理

-- --SET @ETL_DATE = '2025-12-10';
-- --SET @SM4_KEY = 'VFlLSFNUc200MjAyNX5+fg==';

-- ==================== 第一步：不存在的TID写入T_DIM_TID_SET表 ====================

-- 1.1 乘机人证件号TID写入（源数据未加密，需先加密）
INSERT INTO DIM_PROD.T_DIM_TID_SET
(
    TID,
    ETL_DATE,
    CREATE_TIME,
    TID_STATUS
)
SELECT
    DISTINCT
    TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(a.CERT_NO)), FROM_BASE64(@SM4_KEY))) TID,
    @ETL_DATE ETL_DATE,
    NOW() CREATE_TIME,
    1 TID_STATUS
FROM
    ODS_PROD.T_ODS_ZSF_ODR_ORDER_DETAIL_INSURANCE a
        LEFT JOIN DIM_PROD.T_DIM_STRONGID tds ON
                TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(a.CERT_NO)), FROM_BASE64(@SM4_KEY))) = tds.STRONGID
            AND tds.STRONGID_STATUS = 1
 WHERE (a.CREATE_TIME BETWEEN CONCAT(@ETL_DATE, ' 00:00:00') AND CONCAT(@ETL_DATE, ' 23:59:59.999')
     OR a.UPDATE_TIME BETWEEN CONCAT(@ETL_DATE, ' 00:00:00') AND CONCAT(@ETL_DATE, ' 23:59:59.999'))
  AND a.INS_STATUS IN ('3', '6', '7')
  AND tds.TID IS NULL
  AND a.CERT_NO IS NOT NULL
  AND TRIM(a.CERT_NO) != ''
  AND TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(a.CERT_NO)), FROM_BASE64(@SM4_KEY))) IS NOT NULL;

-- 1.2 预订人TID写入（CUSTOMER_ID已加密，需解密后重新加密标准化）
INSERT INTO DIM_PROD.T_DIM_TID_SET
(
    TID,
    ETL_DATE,
    CREATE_TIME,
    TID_STATUS
)
SELECT
    DISTINCT
    TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(SM4_DECRYPT(FROM_BASE64(b.CUSTOMER_ID), FROM_BASE64(@SM4_KEY)))), FROM_BASE64(@SM4_KEY))) TID,
    @ETL_DATE ETL_DATE,
    NOW() CREATE_TIME,
    1 TID_STATUS
FROM
    ODS_PROD.T_ODS_ZSF_ODR_ORDER_DETAIL_INSURANCE a
        LEFT JOIN ODS_PROD.T_ODS_ZSF_ODR_ORDER_CUSTOMER_RELATION b
                  ON a.MAIN_ORDER_ID = b.MAIN_ORDER_ID
        LEFT JOIN DIM_PROD.T_DIM_STRONGID tds ON
                TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(SM4_DECRYPT(FROM_BASE64(b.CUSTOMER_ID), FROM_BASE64(@SM4_KEY)))), FROM_BASE64(@SM4_KEY))) = tds.STRONGID
            AND tds.STRONGID_STATUS = 1
 WHERE (a.CREATE_TIME BETWEEN CONCAT(@ETL_DATE, ' 00:00:00') AND CONCAT(@ETL_DATE, ' 23:59:59.999')
     OR a.UPDATE_TIME BETWEEN CONCAT(@ETL_DATE, ' 00:00:00') AND CONCAT(@ETL_DATE, ' 23:59:59.999'))
  AND a.INS_STATUS IN ('3', '6', '7')
  AND tds.TID IS NULL
  AND b.CUSTOMER_ID IS NOT NULL
  AND TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(SM4_DECRYPT(FROM_BASE64(b.CUSTOMER_ID), FROM_BASE64(@SM4_KEY)))), FROM_BASE64(@SM4_KEY))) IS NOT NULL;

-- ==================== 第二步：模拟IDMapping写入T_DIM_STRONGID表 ====================

-- 2.1 乘机人证件号STRONGID写入（源数据未加密）
INSERT INTO DIM_PROD.T_DIM_STRONGID
(
    STRONGID,
    STRONGID_TYPE,
    TID,
    STRONGID_STATUS,
    CREATE_TIME,
    UPDATE_TIME,
    ETL_DATE
)
SELECT
    DISTINCT
    TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(a.CERT_NO)), FROM_BASE64(@SM4_KEY))) STRONGID,
    IFNULL(sid.CFG_VALUE, a.CERT_TYPE) AS STRONGID_TYPE,
    IFNULL(tds.TID, TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(a.CERT_NO)), FROM_BASE64(@SM4_KEY)))) TID,
    1 STRONGID_STATUS,
    NOW() CREATE_TIME,
    NOW() UPDATE_TIME,
    @ETL_DATE ETL_DATE
FROM
    ODS_PROD.T_ODS_ZSF_ODR_ORDER_DETAIL_INSURANCE a
        LEFT JOIN DIM_PROD.T_DIM_STRONGID tds ON
                TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(a.CERT_NO)), FROM_BASE64(@SM4_KEY))) = tds.STRONGID
            AND tds.STRONGID_STATUS = 1
        LEFT JOIN DWD_PROD.STANDARDIZE_FIELD sid ON a.CERT_TYPE = sid.CFG_CODE
            AND sid.CFG_TYPE = 'DOCUMENT_TYPE'
            AND sid.CFG_TYPE_CHANNEL = 'ZHANGSHANGFEI'
 WHERE (a.CREATE_TIME BETWEEN CONCAT(@ETL_DATE, ' 00:00:00') AND CONCAT(@ETL_DATE, ' 23:59:59.999')
     OR a.UPDATE_TIME BETWEEN CONCAT(@ETL_DATE, ' 00:00:00') AND CONCAT(@ETL_DATE, ' 23:59:59.999'))
  AND a.INS_STATUS IN ('3', '6', '7')
  AND a.CERT_NO IS NOT NULL
  AND TRIM(a.CERT_NO) != ''
  AND TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(a.CERT_NO)), FROM_BASE64(@SM4_KEY))) IS NOT NULL;

-- 2.2 预订人CUSTOMER_ID STRONGID写入（已加密，需解密后重新加密标准化）
INSERT INTO DIM_PROD.T_DIM_STRONGID
