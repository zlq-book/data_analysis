        WHEN a.CERT_TYPE = 'NI' AND LENGTH(SM4_DECRYPT(FROM_BASE64(a.CERT_NO), FROM_BASE64(@SM4_KEY))) = 18
        THEN TRUE
        ELSE FALSE
    END AS IS_CODE_RULE_COMPLIANT,

