(
    PK_ID,
    CN_NAME,
    EN_NAME,
    SEX,
    BIRTHDAY,
    IS_DOUYIN_CARD_PURCHASER,
    CREATE_TIME,
    UPDATE_TIME
)
SELECT
    -- 主键：TID
    IFNULL(tds.TID, TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(SM4_DECRYPT(FROM_BASE64(a.CERT_NO), FROM_BASE64(@SM4_KEY)))), FROM_BASE64(@SM4_KEY)))) AS PK_ID,

    -- 中文姓名（去除空格并转大写）
    UPPER(REPLACE(CONCAT(COALESCE(a.CN_LAST_NAME, ''), COALESCE(a.CN_FIRST_NAME, '')), ' ', '')) AS CN_NAME,

    -- 英文姓名（去除INF/CHD等后缀）
    UPPER(TRIM(CONCAT(COALESCE(a.EN_LAST_NAME, ''), ' ', COALESCE(a.EN_FIRST_NAME, '')))) AS EN_NAME,

    -- 性别标准化
    IFNULL(sid1.CFG_VALUE, a.SEX) AS SEX,

    -- 生日
    CASE WHEN a.BIRTHDAY IS NOT NULL THEN DATE(STR_TO_DATE(a.BIRTHDAY, '%Y-%m-%d')) ELSE NULL END AS BIRTHDAY,

     -- 是否抖音次卡购买人：手机号非空（非NULL/非空字符串）则为TRUE，否则为NULL
    CASE
        WHEN a.MOBILE IS NOT NULL AND TRIM(a.MOBILE) <> '' THEN TRUE
        ELSE NULL
    END AS DOUYIN_CARD_PURCHASER,

    NOW() AS CREATE_TIME,
    NOW() AS UPDATE_TIME

FROM ODS_PROD.T_ODS_ZSF_ODR_ORDER_DETAIL_SECONDARY_DOUYIN a
         LEFT JOIN DIM_PROD.T_DIM_STRONGID tds ON
            TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(SM4_DECRYPT(FROM_BASE64(a.CERT_NO), FROM_BASE64(@SM4_KEY)))), FROM_BASE64(@SM4_KEY))) = tds.STRONGID
        AND tds.STRONGID_STATUS = 1
         LEFT JOIN DWD_PROD.STANDARDIZE_FIELD sid1 ON a.SEX = sid1.CFG_CODE
            AND sid1.CFG_TYPE = 'GENDER' AND sid1.CFG_TYPE_CHANNEL = 'ALL'
WHERE (a.CREATE_TIME BETWEEN CONCAT(@ETL_DATE, ' 00:00:00') AND CONCAT(@ETL_DATE, ' 23:59:59.999')
    OR a.UPDATE_TIME BETWEEN CONCAT(@ETL_DATE, ' 00:00:00') AND CONCAT(@ETL_DATE, ' 23:59:59.999'))
  AND a.CERT_NO IS NOT NULL LIMIT 10;

-- 3.5 写入手机号维表 (T_DIM_MOBILE_DIM)
INSERT INTO DIM_PROD.T_DIM_MOBILE_DIM
(
    SYSTEM_KEY,
    T_ID,
    MOBILE_NUMBER,
    CREATE_TIME,
    UPDATE_TIME
)
SELECT

	-- 主键：TID + 手机号
	CONCAT(
	    COALESCE(IFNULL(tds.TID, TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(SM4_DECRYPT(FROM_BASE64(a.CERT_NO), FROM_BASE64(@SM4_KEY)))), FROM_BASE64(@SM4_KEY)))), ''),  -- 修正括号闭合+移除内部AS
	    COALESCE(TO_BASE64(SM4_ENCRYPT(PHONE_NUM, FROM_BASE64(@SM4_KEY))), '')
	) AS SYSTEM_KEY,

	-- TID
	IFNULL(
	    tds.TID,
	    TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(SM4_DECRYPT(FROM_BASE64(a.CERT_NO), FROM_BASE64(@SM4_KEY)))), FROM_BASE64(@SM4_KEY)))
	) AS T_ID,

	-- 手机号（加密）
	TO_BASE64(SM4_ENCRYPT(PHONE_NUM, FROM_BASE64(@SM4_KEY)))  AS MOBILE_NUMBER,

	NOW() AS CREATE_TIME,
	NOW() AS UPDATE_TIME

FROM ODS_PROD.T_ODS_ZSF_ODR_ORDER_DETAIL_SECONDARY_DOUYIN a
         LEFT JOIN DIM_PROD.T_DIM_STRONGID tds ON
            TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(SM4_DECRYPT(FROM_BASE64(a.PHONE_NUM), FROM_BASE64(@SM4_KEY)))), FROM_BASE64(@SM4_KEY))) = tds.STRONGID
        AND tds.STRONGID_STATUS = 1
WHERE (a.CREATE_TIME BETWEEN CONCAT(@ETL_DATE, ' 00:00:00') AND CONCAT(@ETL_DATE, ' 23:59:59.999')
    OR a.UPDATE_TIME BETWEEN CONCAT(@ETL_DATE, ' 00:00:00') AND CONCAT(@ETL_DATE, ' 23:59:59.999'))
  AND a.PHONE_NUM IS NOT NULL;

