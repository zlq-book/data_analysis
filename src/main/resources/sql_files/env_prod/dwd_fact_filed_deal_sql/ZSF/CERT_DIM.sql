-- 3.3 写入证件信息维表 (T_DIM_CERT_DIM)
INSERT INTO DIM_PROD.T_DIM_CERT_DIM
(
    SYSTEM_KEY,
    T_ID,
    CERT_TYPE,
    CERT_NUMBER,
    CERT_EXPIRE_DATE,
    CURRENT_CERT_HIGHEST_PRIORITY,
    UPDATE_TIME,
    CREATE_TIME
)
SELECT
    -- 主键：TID + 证件类型 + 证件号
    CONCAT(
            COALESCE(IFNULL(tds.TID, TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(SM4_DECRYPT(FROM_BASE64(a.CERT_NO), FROM_BASE64(@SM4_KEY)))), FROM_BASE64(@SM4_KEY)))), ''),
            COALESCE(IFNULL(sid1.CFG_VALUE, a.CERT_TYPE), ''),
            COALESCE(TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(SM4_DECRYPT(FROM_BASE64(a.CERT_NO), FROM_BASE64(@SM4_KEY)))), FROM_BASE64(@SM4_KEY))), '')
        ) AS SYSTEM_KEY,

    -- TID
    IFNULL(tds.TID, TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(SM4_DECRYPT(FROM_BASE64(a.CERT_NO), FROM_BASE64(@SM4_KEY)))), FROM_BASE64(@SM4_KEY)))) AS T_ID,
    -- 证件类型标准化
    IFNULL(sid1.CFG_VALUE, a.CERT_TYPE) AS CERT_TYPE,
    -- 证件号码（加密）
    TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(SM4_DECRYPT(FROM_BASE64(a.CERT_NO), FROM_BASE64(@SM4_KEY)))), FROM_BASE64(@SM4_KEY))) AS CERT_NUMBER,
    -- 证件过期日期
    CASE WHEN a.EXPIRATION_DATE IS NOT NULL THEN STR_TO_DATE(a.EXPIRATION_DATE, '%Y-%m-%d') ELSE NULL END AS CERT_EXPIRE_DATE,
    -- 当前证件最高优先级
    1 AS CURRENT_CERT_HIGHEST_PRIORITY,
    NOW() AS UPDATE_TIME,
    NOW() AS CREATE_TIME
FROM ODS_PROD.T_ODS_ZSF_ODR_ORDER_DETAIL_SECONDARY_DOUYIN a
         LEFT JOIN DIM_PROD.T_DIM_STRONGID tds ON
            TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(SM4_DECRYPT(FROM_BASE64(a.CERT_NO), FROM_BASE64(@SM4_KEY)))), FROM_BASE64(@SM4_KEY))) = tds.STRONGID
        AND tds.STRONGID_STATUS = 1
         LEFT JOIN DWD_PROD.STANDARDIZE_FIELD sid1 ON a.CERT_TYPE = sid1.CFG_CODE
            AND sid1.CFG_TYPE = 'DOCUMENT_TYPE' AND sid1.CFG_TYPE_CHANNEL = 'ALL'
WHERE (a.CREATE_TIME BETWEEN CONCAT(@ETL_DATE, ' 00:00:00') AND CONCAT(@ETL_DATE, ' 23:59:59.999')
    OR a.UPDATE_TIME BETWEEN CONCAT(@ETL_DATE, ' 00:00:00') AND CONCAT(@ETL_DATE, ' 23:59:59.999'))
  AND a.CERT_NO IS NOT NULL;





