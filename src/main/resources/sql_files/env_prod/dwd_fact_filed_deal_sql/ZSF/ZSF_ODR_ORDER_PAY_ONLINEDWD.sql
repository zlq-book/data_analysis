-- 任务名 ZSF_ODR_ORDER_PAY_ONLINE2DWD
-- 掌尚飞-在线支付信息表 T_ODS_ZSF_ODR_ORDER_PAY_ONLINE 写入事实表 T_DWD_PAYDETAILS_ORD_FACT
-- 主键：数据源代号+业务大订单编号+支付流水号 数据源代号：SCAPP
-- 说明：掌尚飞在线支付数据T+1入库后，PAY_STATUS='3'（支付成功）的数据进入本表
-- 连表：ODR_ORDER_PAY_ONLINE支付表的ORDER_PAY_ID=ODR_ORDER_PAY支付记录表的ID，获取ORDER_NO订单号

-- 1、不存在的TID写入T_DIM_TID_SET表
INSERT INTO DIM_PROD.T_DIM_TID_SET
(
    TID,
    ETL_DATE,
    CREATE_TIME,
    TID_STATUS
)
SELECT
    DISTINCT
    TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(SM4_DECRYPT(FROM_BASE64(a.CUSTOMER_ID), FROM_BASE64(@SM4_KEY)))), FROM_BASE64(@SM4_KEY))) TID,
    @ETL_DATE ETL_DATE,
    CURRENT_TIMESTAMP(3) CREATE_TIME,
    1 TID_STATUS
FROM
    ODS_PROD.T_ODS_ZSF_ODR_ORDER_PAY_ONLINE a
INNER JOIN ODS_PROD.T_ODS_ZSF_ODR_ORDER_PAY b
    ON a.ORDER_PAY_ID = b.ID
LEFT JOIN DIM_PROD.T_DIM_STRONGID tds ON
    TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(SM4_DECRYPT(FROM_BASE64(a.CUSTOMER_ID), FROM_BASE64(@SM4_KEY)))), FROM_BASE64(@SM4_KEY))) = tds.STRONGID
    AND tds.STRONGID_STATUS = 1
WHERE (a.CREATE_TIME BETWEEN CONCAT(@ETL_DATE, ' 00:00:00') AND CONCAT(@ETL_DATE, ' 23:59:59.999')
    OR a.UPDATE_TIME BETWEEN CONCAT(@ETL_DATE, ' 00:00:00') AND CONCAT(@ETL_DATE, ' 23:59:59.999'))
  AND a.PAY_STATUS = '3'
  AND tds.TID IS NULL
  AND a.CUSTOMER_ID IS NOT NULL
  AND TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(SM4_DECRYPT(FROM_BASE64(a.CUSTOMER_ID), FROM_BASE64(@SM4_KEY)))), FROM_BASE64(@SM4_KEY))) IS NOT NULL;

-- 2、模拟IDMapping写入T_DIM_STRONGID表
INSERT INTO DIM_PROD.T_DIM_STRONGID
(
    STRONGID,
    STRONGID_TYPE,
    TID,
    STRONGID_STATUS,
    CREATE_TIME,
    UPDATE_TIME,
    ETL_DATE
