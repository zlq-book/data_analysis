--写入强ID表，证件,只写入没有的强ID
INSERT INTO DIM_PROD.T_DIM_STRONGID (STRONGID, STRONGID_TYPE, TID, CREATE_TIME, UPDATE_TIME, ETL_DATE)
SELECT CERT_NO AS STRONGID, STRONGID_TYPE, TID, now() AS CREATE_TIME,now() AS UPDATE_TIME, now() AS ETL_DATE FROM (
SELECT dpic.CERT_NO, dpic.STRONGID_TYPE, CASE WHEN sid.TID IS NULL THEN dpic.CERT_NO ELSE NULL END AS TID
FROM (
SELECT TO_BASE64(SM4_ENCRYPT(UPPER(TRIM(SM4_DECRYPT(FROM_BASE64(CERT_NO), FROM_BASE64(@SM4_KEY)))), FROM_BASE64(@SM4_KEY))) AS CERT_NO,
     IFNULL(sid.CFG_VALUE, ID_TYPE) AS STRONGID_TYPE
FROM ODS_PROD.T_ODS_LYGJ_DEPART_PASSENGER_INFO toldpi
LEFT JOIN DWD_PROD.STANDARDIZE_FIELD sid ON ID_TYPE=sid.CFG_CODE
AND sid.CFG_TYPE = 'DOCUMENT_TYPE' AND sid.CFG_TYPE_CHANNEL ='LUYAN_STEWARD'
WHERE CERT_NO IS NOT NULL
AND ETL_DATE >= @ETL_DATE -- 取数时间
) dpic
LEFT JOIN DIM_PROD.T_DIM_STRONGID sid ON dpic.CERT_NO = sid.STRONGID AND sid.STRONGID_STATUS=1
) finaldpi WHERE finaldpi.TID IS NOT NULL;

