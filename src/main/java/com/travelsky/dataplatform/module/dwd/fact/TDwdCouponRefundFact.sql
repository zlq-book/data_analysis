CREATE TABLE IF NOT EXISTS T_DWD_TRP_COUPON_REFUND_FACT (
    PK_ID VARCHAR(600) NOT NULL COMMENT '主键ID (订单号+券码)',
    ORDER_NUMBER VARCHAR(500) REPLACE NULL COMMENT '订单号',
    REFUND_CHANNEL VARCHAR(500) REPLACE NULL COMMENT '退订渠道',
    PURCHASE_DATE VARCHAR(50) REPLACE NULL COMMENT '购买日期',
    PURCHASE_TIME VARCHAR(50) REPLACE NULL COMMENT '购买时间',
    VOUCHER_NAME VARCHAR(500) REPLACE NULL COMMENT '券名称',
    VOUCHER_AMOUNT DECIMAL(20,2) REPLACE NULL COMMENT '券面额',
